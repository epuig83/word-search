const fs = require("node:fs");
const path = require("node:path");
const { createHash } = require("node:crypto");

// The only maintained list of offline assets. The generated manifest is checked in
// so opening the app or serving the repository never requires a runtime build.
const APP_SHELL = [
  "index.html", "es.html", "en.html", "styles.css", "font-init.js",
  "assets/fonts/andika-regular-latin.woff2", "assets/fonts/andika-bold-latin.woff2",
  "data.js", "i18n.js", "core.js", "app-helpers.js", "app-storage.js",
  "app-modal.js", "app-board.js", "app-teacher.js", "app-session.js", "app-offline.js", "app-print.js", "app.js",
  "vendor/canvas-confetti.browser.js", "manifest.webmanifest", "icon.svg",
  "icon-192.png", "icon-512.png", "icon-maskable.png", "og-image.png",
];
const root = path.resolve(__dirname, "..");
const readSource = filename => fs.readFileSync(path.join(root, filename));
const hash = content => createHash("sha256").update(content).digest("base64");

function buildOfflineManifest(readFile = readSource) {
  const assets = APP_SHELL.map(filename => ({ url: `./${filename}`, integrity: `sha256-${hash(readFile(filename))}` }));
  // Changing worker logic also gets a distinct cache, even if no asset changed.
  const revision = createHash("sha256").update(JSON.stringify(assets)).update(readFile("sw.js")).digest("hex");
  return { revision, assets };
}

function serializeOfflineManifest(manifest) {
  return `// Generated by scripts/generate-offline-manifest.js. Do not edit.\nself.WORD_SEARCH_OFFLINE = ${JSON.stringify(manifest, null, 2)};\n`;
}

if (require.main === module) {
  const outputPath = path.join(root, "offline-manifest.js");
  const output = serializeOfflineManifest(buildOfflineManifest());
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
      throw new Error("offline-manifest.js is out of date. Run pnpm build:offline after updating the app or localized pages.");
    }
  } else {
    fs.writeFileSync(outputPath, output);
  }
}

module.exports = { APP_SHELL, buildOfflineManifest, serializeOfflineManifest };
